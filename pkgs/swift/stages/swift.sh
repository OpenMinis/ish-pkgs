#!/bin/sh
# The musl-host Swift compiler: direct cmake, host SDK = LINUX_STATIC,
# bootstrapped with the image's swiftc (BOOTSTRAPPING_MODE=HOSTTOOLS).
. "$PKG/stages/common.sh"
mkdir -p "$SWIFT"; cd "$SWIFT"
N=$NATIVE/bin
FLAGS="-Wno-unknown-warning-option -fno-stack-protector -D_GNU_SOURCE -DHAVE_DECL_PROGRAM_INVOCATION_SHORT_NAME"
if [ ! -f CMakeCache.txt ]; then
run swift-configure cmake -G Ninja \
 -DCMAKE_TOOLCHAIN_FILE="$PKG/files/swift-toolchain.cmake" \
 -DCMAKE_C_COMPILER=/usr/bin/clang -DCMAKE_CXX_COMPILER=/usr/bin/clang++ -DCMAKE_Swift_COMPILER=/usr/bin/swiftc \
 -DCMAKE_AR=/usr/bin/llvm-ar -DCMAKE_RANLIB=/usr/bin/llvm-ranlib \
 -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX=/usr \
 "-DCMAKE_C_FLAGS=$FLAGS" "-DCMAKE_CXX_FLAGS=$FLAGS" \
 -DLLVM_ENABLE_ASSERTIONS=OFF \
 -DSWIFT_HOST_VARIANT=linux -DSWIFT_HOST_VARIANT_SDK=LINUX_STATIC -DSWIFT_HOST_VARIANT_ARCH=aarch64 \
 -DSWIFT_SDKS=LINUX_STATIC -DSWIFT_MUSL_PATH=/usr/local/musl -DSWIFT_SDK_LINUX_STATIC_ARCHITECTURES=aarch64 \
 -DSWIFT_PRIMARY_VARIANT_SDK=LINUX_STATIC -DSWIFT_PRIMARY_VARIANT_ARCH=aarch64 \
 -DBOOTSTRAPPING_MODE=HOSTTOOLS \
 -DSWIFT_NATIVE_SWIFT_TOOLS_PATH=/usr/bin -DSWIFT_NATIVE_LLVM_TOOLS_PATH="$N" -DSWIFT_NATIVE_CLANG_TOOLS_PATH="$N" \
 -DLLVM_TABLEGEN="$N/llvm-tblgen" \
 -DSWIFT_PATH_TO_SWIFT_SDK=$SDK \
 "-DSWIFT_COMPILER_SOURCES_SDK_FLAGS=-sdk;$SDK;-resource-dir;$SDK/usr/lib/swift_static" \
 -DClang_DIR="$LLVM/lib/cmake/clang" -DLLVM_DIR="$LLVM/lib/cmake/llvm" \
 -DSWIFT_PATH_TO_CMARK_SOURCE="$W/src/cmark" -DSWIFT_PATH_TO_CMARK_BUILD="$B/cmark-linux-static-aarch64" \
 -DSWIFT_PATH_TO_SWIFT_SYNTAX_SOURCE="$W/src/swift-syntax" -DSWIFT_BUILD_SWIFT_SYNTAX=TRUE \
 -DSWIFT_PATH_TO_STRING_PROCESSING_SOURCE="$W/src/swift-experimental-string-processing" \
 -DSWIFT_PATH_TO_LIBDISPATCH_SOURCE="$W/src/swift-corelibs-libdispatch" \
 -DSWIFT_INCLUDE_TOOLS=TRUE -DSWIFT_INCLUDE_TESTS=FALSE -DSWIFT_INCLUDE_TEST_BINARIES=FALSE -DSWIFT_INCLUDE_DOCS=FALSE \
 -DSWIFT_BUILD_DYNAMIC_STDLIB=FALSE -DSWIFT_BUILD_STATIC_STDLIB=FALSE \
 -DSWIFT_BUILD_DYNAMIC_SDK_OVERLAY=FALSE -DSWIFT_BUILD_STATIC_SDK_OVERLAY=FALSE \
 -DSWIFT_BUILD_REMOTE_MIRROR=FALSE -DSWIFT_BUILD_SOURCEKIT=FALSE -DSWIFT_BUILD_LIBEXEC=FALSE \
 -DSWIFT_BUILD_PERF_TESTSUITE=FALSE -DSWIFT_BUILD_EXAMPLES=FALSE -DSWIFT_BUILD_CLANG_OVERLAYS=FALSE \
 -DSWIFT_ENABLE_DISPATCH=FALSE -DSWIFT_SHOULD_BUILD_EMBEDDED_STDLIB=FALSE \
 -DSWIFT_ENABLE_EXPERIMENTAL_STRING_PROCESSING=TRUE \
 -DSWIFT_ENABLE_EXPERIMENTAL_DIFFERENTIABLE_PROGRAMMING=TRUE -DSWIFT_ENABLE_EXPERIMENTAL_CONCURRENCY=TRUE \
 -DSWIFT_ENABLE_EXPERIMENTAL_CXX_INTEROP=TRUE -DSWIFT_ENABLE_EXPERIMENTAL_DISTRIBUTED=TRUE \
 -DSWIFT_ENABLE_EXPERIMENTAL_OBSERVATION=TRUE -DSWIFT_ENABLE_SYNCHRONIZATION=TRUE -DSWIFT_ENABLE_VOLATILE=TRUE \
 -DSWIFT_ENABLE_BACKTRACING=TRUE -DSWIFT_ENABLE_RUNTIME_MODULE=TRUE \
 -DSWIFT_PARALLEL_LINK_JOBS=2 -DSWIFT_USE_LINKER=lld \
 -DSWIFT_DARWIN_XCRUN_TOOLCHAIN=default \
 -DUUID_INCLUDE_DIR="$EXTRA/include" -DUUID_LIBRARY="$EXTRA/lib/libuuid.a" \
 "$W/src/swift"
fi
# swift-frontend links the Swift-written parts (SwiftCompilerSources, swift-syntax)
# against the image's static runtime, so the runtime must already be patched.
"$PKG/stages/patch-sdk.sh" check
run swift-build ninja -k 20 -j"$JOBS" swift-frontend
[ -x bin/swift-frontend ]
